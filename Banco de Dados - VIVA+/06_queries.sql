USE movi;

-- CONSULTAS BASICAS

SELECT * FROM USUARIO;

SELECT * FROM META;

SELECT * FROM ATIVIDADE;

SELECT * FROM REGISTRO_ATIVIDADES;

SELECT * FROM CATEGORIA_LOCAL;

SELECT * FROM LOCAL_;

SELECT * FROM USUARIO_VISUALIZA_LOCAL;

SELECT * FROM ALIMENTO;

SELECT * FROM USUARIO_CONSULTA_ALIMENTO;


-- FILTROS

SELECT *
FROM META
WHERE status_meta = 'ATIVA';

SELECT *
FROM USUARIO
WHERE tipo_usuario = 'COMUM';


-- ORDENACAO

SELECT *
FROM META
ORDER BY data_inicio ASC;

SELECT *
FROM REGISTRO_ATIVIDADES
ORDER BY calorias_queimadas DESC;


-- ESTATISTICAS POR USUARIO

SELECT
    ID_Usuario,
    COUNT(*) AS total_atividades
FROM REGISTRO_ATIVIDADES
GROUP BY ID_Usuario;

SELECT
    ID_Usuario,
    SUM(calorias_queimadas) AS total_calorias
FROM REGISTRO_ATIVIDADES
GROUP BY ID_Usuario;

SELECT
    ID_Usuario,
    AVG(duracao_minuto) AS media_duracao
FROM REGISTRO_ATIVIDADES
GROUP BY ID_Usuario;


-- DASHBOARD DE ATIVIDADES

SELECT
    USUARIO.nome,
    COUNT(REGISTRO_ATIVIDADES.ID_Registro) AS total_atividades,
    SUM(REGISTRO_ATIVIDADES.calorias_queimadas) AS total_calorias,
    AVG(REGISTRO_ATIVIDADES.duracao_minuto) AS media_duracao
FROM USUARIO
JOIN REGISTRO_ATIVIDADES
    ON USUARIO.ID_Usuario = REGISTRO_ATIVIDADES.ID_Usuario
GROUP BY USUARIO.ID_Usuario, USUARIO.nome;

-- HAVING --

SELECT
	ID_Usuario,
    COUNT(*) AS total_atividades
    FROM REGISTRO_ATIVIDADES
    GROUP BY ID_Usuario
    HAVING COUNT(*) >= 1;
    
SELECT
	ID_Usuario,
    COUNT(*) AS total_atividades
FROM REGISTRO_ATIVIDADES
GROUP BY ID_Usuario
HAVING COUNT(*) >= 5;

-- LEFT JOIN --

SELECT
    USUARIO.nome,
    REGISTRO_ATIVIDADES.ID_Registro
FROM USUARIO
LEFT JOIN REGISTRO_ATIVIDADES
    ON USUARIO.ID_Usuario = REGISTRO_ATIVIDADES.ID_Usuario;
    